/* noema-lite — ESLint (flat config): npm run lint covers the whole repo.
   · src/**: typescript-eslint strict-type-checked + the dependency rule of the architecture (eslint-plugin-boundaries,
     docs/ARCHITECTURE.md), no empty catch, and no DOM / network / storage / clock in the pure layers.
   · the older JavaScript (engine/, tools/, tests/, cloud/, skill/): parsed only (syntax errors fail the lint), no style rules;
     it is replaced in phase 3, not reformatted now.
   This file is CommonJS like the rest of the repo's .js (only src/ is ES modules: src/package.json). */
'use strict';
const tseslint = require('typescript-eslint');
const boundaries = require('eslint-plugin-boundaries');

/* ---------- the layers of src/ and who may import whom ---------- */
const ELEMENTS = [
  { type: 'kernel', pattern: 'src/kernel', partialMatch: false },
  { type: 'contracts', pattern: 'src/contracts', partialMatch: false },
  { type: 'ports', pattern: 'src/ports', partialMatch: false },
  { type: 'domain', pattern: 'src/features/*/domain', partialMatch: false, capture: ['feature'] },
  { type: 'application', pattern: 'src/features/*/application', partialMatch: false, capture: ['feature'] },
  // a feature's screens (phase 3): Lit components on the kit, driven by the feature's domain and application
  { type: 'feature-ui', pattern: 'src/features/*/ui', partialMatch: false, capture: ['feature'] },
  { type: 'plugins', pattern: 'src/plugins', partialMatch: false },
  { type: 'engines', pattern: 'src/engines', partialMatch: false },
  { type: 'adapters', pattern: 'src/adapters', partialMatch: false },
  // the UI's tests (src/ui/test/) wire the components to the memory adapters, as a composition root would (listed before 'ui',
  // which would match them too)
  { type: 'ui-test', pattern: 'src/ui/test', partialMatch: false },
  { type: 'ui', pattern: 'src/ui', partialMatch: false },
  { type: 'connector', pattern: 'src/connector', partialMatch: false },
  { type: 'composition', pattern: 'src/composition', partialMatch: false },
];
/** kernel ← contracts ← ports ← domain / application / plugins / engines; adapters on ports, contracts and kernel; only
    composition wires adapters to ports (and nothing imports composition) */
const MAY_IMPORT = {
  kernel: ['kernel'],
  contracts: ['kernel', 'contracts'],
  ports: ['kernel', 'contracts', 'ports'],
  domain: ['kernel', 'contracts', 'ports', 'domain'],
  application: ['kernel', 'contracts', 'ports', 'domain', 'application'],
  plugins: ['kernel', 'contracts', 'ports', 'plugins'],
  engines: ['kernel', 'contracts', 'ports', 'plugins', 'engines'],
  adapters: ['kernel', 'contracts', 'ports', 'adapters'],
  // the UI (src/ui: the component kit, the router, the frame) is a driving adapter: it reaches the core through the ports
  ui: ['kernel', 'contracts', 'ports', 'ui'],
  'ui-test': ['kernel', 'contracts', 'ports', 'adapters', 'ui'],
  // a feature's screens: the kit (ui), the feature's domain and use cases, the ports; never an adapter (the root hands them in)
  'feature-ui': ['kernel', 'contracts', 'ports', 'domain', 'application', 'ui', 'feature-ui'],
  connector: ['kernel', 'contracts', 'ports', 'domain', 'application', 'plugins', 'engines', 'connector'],
  composition: ELEMENTS.map(e => e.type),
};
/** the layers that never touch the DOM, the network, storage or the clock directly (they get them through ports) */
const PURE = ['src/kernel/**', 'src/contracts/**', 'src/features/*/domain/**', 'src/features/*/application/**', 'src/plugins/**', 'src/engines/**'];
const IMPURE_GLOBALS = ['window', 'document', 'navigator', 'location', 'localStorage', 'sessionStorage', 'indexedDB', 'caches', 'fetch', 'XMLHttpRequest', 'WebSocket', 'EventSource', 'setTimeout', 'setInterval', 'requestAnimationFrame']
  .map(name => ({ name, message: 'A pure layer reaches the outside world only through a port (src/ports/).' }));

module.exports = tseslint.config(
  {
    ignores: ['node_modules/**', '.claude/**', 'dist/**', 'build/**', 'data/**', '_to_delete/**', '**/vendor/**', 'library/**', 'accounts/**', 'tests/fixtures/**',
      // generated by tools/build.py (never committed)
      'engine/engine.js', 'engine/langui.js', 'engine/authoring.js', 'engine/activity_author_schemas.js', 'engine/i18n/**',
      'src/contracts/generated/**', 'src/contracts/validate.ts', 'engine/contracts.js', 'engine/tokens.css'],
  },
  { linterOptions: { reportUnusedDisableDirectives: 'off' } },

  /* ---------- the older JavaScript: parsed, not styled ---------- */
  { files: ['**/*.js', '**/*.cjs'], languageOptions: { ecmaVersion: 'latest', sourceType: 'commonjs' } },
  { files: ['engine/**/*.js', 'config*.js'], languageOptions: { sourceType: 'script' } },
  { files: ['**/*.mjs'], languageOptions: { ecmaVersion: 'latest', sourceType: 'module' } },

  /* ---------- the engines' own code (src/engines/**\/*.js): plain ES modules (src/package.json), typed at their edge by a .d.ts
     beside each (the TypeScript rules apply there and to the .ts around them). Here only what the architecture asks of a pure
     layer: no empty catch and no DOM / network / storage / clock (rules below, PURE). ---------- */
  { files: ['src/**/*.js'], languageOptions: { ecmaVersion: 'latest', sourceType: 'module' }, rules: { 'no-empty': ['error', { allowEmptyCatch: false }] } },
  { files: ['src/**/vendor/**'], languageOptions: { sourceType: 'commonjs' } },

  /* ---------- src/: TypeScript, strict ---------- */
  ...tseslint.configs.strictTypeChecked.map(c => ({ ...c, files: ['src/**/*.ts'] })),
  {
    files: ['src/**/*.ts'],
    languageOptions: { parserOptions: { projectService: true, tsconfigRootDir: __dirname } },
    plugins: { boundaries },
    settings: {
      'boundaries/elements': ELEMENTS,
      'boundaries/include': ['src/**/*.ts'],
      'import/resolver': { typescript: { project: require('path').join(__dirname, 'tsconfig.json') } },   // the @/ paths and .ts imports, as tsc and esbuild resolve them
    },
    rules: {
      'boundaries/dependencies': ['error', {
        default: 'disallow',
        policies: Object.entries(MAY_IMPORT).map(([from, to]) => ({ from: { element: { type: from } }, allow: { to: { element: { types: to } } } })),
      }],
      'boundaries/no-unknown-files': 'error',   // every file of src/ belongs to a layer
      'no-empty': ['error', { allowEmptyCatch: false }],
      'no-restricted-syntax': ['error',
        { selector: 'CatchClause > BlockStatement[body.length=0]', message: 'No empty catch: handle the error, return a Result, or report it (ErrorReporter port).' }],
      '@typescript-eslint/consistent-type-imports': 'error',
      '@typescript-eslint/restrict-template-expressions': ['error', { allowNumber: true }],
      // node:test's test() / describe() / it() return promises the runner owns and awaits
      '@typescript-eslint/no-floating-promises': ['error', {
        allowForKnownSafeCalls: [{ from: 'package', package: 'node:test', name: ['test', 'describe', 'it', 'suite'] }],
      }],
    },
  },
  {
    files: PURE,
    rules: {
      'no-restricted-globals': ['error', ...IMPURE_GLOBALS],
      'no-restricted-syntax': ['error',
        { selector: 'CatchClause > BlockStatement[body.length=0]', message: 'No empty catch: handle the error, return a Result, or report it (ErrorReporter port).' },
        { selector: "CallExpression[callee.object.name='Date'][callee.property.name='now']", message: 'The clock is a port (src/ports/clock): no Date.now() in a pure layer.' },
        { selector: "NewExpression[callee.name='Date'][arguments.length=0]", message: 'The clock is a port (src/ports/clock): no new Date() in a pure layer.' }],
    },
  },
);
