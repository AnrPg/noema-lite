/* Build the runtime catalogs: i18n/<component>/<locale>.arb (+ drafts/) → engine/i18n/<locale>.js
   ({ m: approved messages, d: Claude's drafts, shown only while the locale is in 'preview' }) and the pseudo-locales
   en-XA (accented, +40 %, in [brackets]) and ar-XB (right-to-left marks around every message).
   Usage: node tools/i18n/build.js   (tools/build.py runs it) */
const fs = require('fs'), path = require('path');
const { ROOT, LOCALES, loadAll, messages, parse, print } = require('./icu');
const OUT = path.join(ROOT, 'engine', 'i18n');
/** Components the app never reads at run time: the account e-mails (i18n/email → tools/i18n/emails.js → cloud/email/). check.js still checks them. */
const NOT_IN_APP = new Set(['email']);

const ACC = { a: 'á', b: 'ƀ', c: 'ç', d: 'ď', e: 'é', f: 'ƒ', g: 'ĝ', h: 'ĥ', i: 'í', j: 'ĵ', k: 'ķ', l: 'ļ', m: 'ɱ', n: 'ñ', o: 'ó', p: 'þ', q: 'ǫ', r: 'ŕ', s: 'š', t: 'ţ', u: 'ú', v: 'ṽ', w: 'ŵ', x: 'ẋ', y: 'ý', z: 'ž',
  A: 'Á', B: 'Ɓ', C: 'Ç', D: 'Ď', E: 'É', F: 'Ƒ', G: 'Ĝ', H: 'Ĥ', I: 'Í', J: 'Ĵ', K: 'Ķ', L: 'Ļ', M: 'Ṁ', N: 'Ñ', O: 'Ó', P: 'Þ', Q: 'Ǫ', R: 'Ŕ', S: 'Š', T: 'Ţ', U: 'Ú', V: 'Ṽ', W: 'Ŵ', X: 'Ẋ', Y: 'Ý', Z: 'Ž' };
const accent = s => s.replace(/[A-Za-z]/g, ch => ACC[ch] || ch);
const longer = s => { const pad = Math.round(s.replace(/\s/g, '').length * 0.4); return s + (pad ? ' ' + '·'.repeat(Math.min(pad, 40)) : ''); };
function pseudo(msg, rtl) {
  let ast; try { ast = parse(msg); } catch (e) { return msg; }
  const body = print(ast, s => rtl ? accent(s) : accent(s));
  return rtl ? `‮${body}‬` : `[${longer(body)}]`;
}
function build() {
  const all = loadAll(), keep = o => Object.fromEntries(Object.entries(o).filter(([comp]) => !NOT_IN_APP.has(comp)));
  const cats = keep(all.cats), drafts = keep(all.drafts);
  const merged = {}, mergedD = {};
  for (const [comp, byLoc] of Object.entries(cats)) for (const [loc, arb] of Object.entries(byLoc)) Object.assign(merged[loc] = merged[loc] || {}, messages(arb));
  for (const [comp, byLoc] of Object.entries(drafts)) for (const [loc, arb] of Object.entries(byLoc)) Object.assign(mergedD[loc] = mergedD[loc] || {}, messages(arb));
  fs.mkdirSync(OUT, { recursive: true });
  for (const f of fs.readdirSync(OUT)) if (f.endsWith('.js')) fs.unlinkSync(path.join(OUT, f));
  const sensitive = [];   // keys whose drafts are never shown (legal, billing, safety): "@key": {"x-sensitive": true}
  for (const byLoc of Object.values(cats)) for (const [k, v] of Object.entries(byLoc.en || {})) if (k.startsWith('@') && v && v['x-sensitive']) sensitive.push(k.slice(1));
  const write = (loc, m, d) => {
    const body = JSON.stringify({ m, ...(d && Object.keys(d).length ? { d } : {}), ...(loc === 'en' && sensitive.length ? { s: sensitive } : {}) });
    fs.writeFileSync(path.join(OUT, loc + '.js'), `/* GENERATED by tools/i18n/build.js from i18n/<component>/${loc}.arb — do not edit (docs/i18n.md) */\n(window.NOEMA_I18N = window.NOEMA_I18N || {})[${JSON.stringify(loc)}] = ${body.replace(/<\//g, '<\\/')};\n`);
  };
  const en = merged.en || {};
  for (const loc of LOCALES) {
    const m = merged[loc] || {}, d = {};
    for (const [k, v] of Object.entries(mergedD[loc] || {})) if (m[k] == null && en[k] != null) d[k] = v;   // a draft only where nothing approved exists
    if (loc === 'en' || Object.keys(m).length || Object.keys(d).length) write(loc, m, d);
  }
  write('en-XA', Object.fromEntries(Object.entries(en).map(([k, v]) => [k, pseudo(v, false)])));
  write('ar-XB', Object.fromEntries(Object.entries(en).map(([k, v]) => [k, pseudo(v, true)])));
  console.log(`i18n → engine/i18n/: ${Object.keys(en).length} keys · ` + LOCALES.filter(l => l !== 'en').map(l => `${l} ${Object.keys(merged[l] || {}).length}${Object.keys(mergedD[l] || {}).length ? '+' + Object.keys(mergedD[l]).length + 'd' : ''}`).join(' · '));
}
if (require.main === module) build();
module.exports = { build, pseudo, NOT_IN_APP };
