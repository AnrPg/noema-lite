#!/usr/bin/env node
/* Bundle the Claude connector (src/composition/connector.ts) into one ES module with esbuild: the Netlify function
   dist/functions/mcp.mjs (docs/CLAUDE_CONNECTOR.md §Build).
     · `legacy:<path>` imports become the text of that file of the repository (the app's engine/*.js, run by
       src/connector/engine/legacy.ts in a scope of their own: one copy, the app's own file);
     · `virtual:noema-connector-data` becomes the JSON tools/build.py collects (public config + documents).
   Usage: node tools/connector_bundle.mjs --data <data.json> --out <file.mjs>   (tools/build.py site runs it)
   or import { bundleConnector } from './connector_bundle.mjs' (the tests bundle with their own data). */
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ENTRY = 'src/composition/connector.ts';
/** The paths the function answers on (the MCP endpoint and the OAuth protected-resource metadata, src/connector/router.ts):
    a literal `export const config` at the end of the bundle, where Netlify reads it statically. */
export const NETLIFY_CONFIG = 'export const config = { path: ["/mcp", "/.well-known/oauth-protected-resource", "/.well-known/oauth-protected-resource/mcp"] };';

function plugin(root, data) {
  return {
    name: 'noema-connector',
    setup(build) {
      build.onResolve({ filter: /^legacy:/ }, a => {
        const rel = a.path.slice('legacy:'.length);
        const abs = path.resolve(root, rel);
        if (!abs.startsWith(root + path.sep)) return { errors: [{ text: `legacy import outside the repository: ${a.path}` }] };
        return { path: abs, namespace: 'legacy' };
      });
      build.onLoad({ filter: /.*/, namespace: 'legacy' }, a => ({ contents: 'export default ' + JSON.stringify(readFileSync(a.path, 'utf8')) + ';\n', loader: 'js', watchFiles: [a.path] }));
      build.onResolve({ filter: /^virtual:noema-connector-data$/ }, () => ({ path: 'data', namespace: 'noema-data' }));
      build.onLoad({ filter: /.*/, namespace: 'noema-data' }, () => ({ contents: 'export default ' + JSON.stringify(data) + ';\n', loader: 'js' }));
    },
  };
}

/** The esbuild options of the connector (helper of tools/esbuild.mjs: the same entry, format and plugin). */
export function connectorBuildOptions({ root = ROOT, outfile, data }) {
  if (!data?.config?.siteUrl || !data.config.supabaseUrl || !data.config.supabaseKey) throw new Error('connector data: config needs siteUrl, supabaseUrl and supabaseKey');
  return {
    absWorkingDir: root,
    entryPoints: [path.join(root, ENTRY)],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    charset: 'utf8',
    legalComments: 'none',
    banner: { js: '/* GENERATED by tools/connector_bundle.mjs from src/composition/connector.ts (src/connector, engine/*.js) — do not edit */' },
    footer: { js: NETLIFY_CONFIG },
    plugins: [plugin(root, data)],
    logLevel: 'warning',
  };
}

export async function bundleConnector(o) {
  const esbuild = await import('esbuild');
  const r = await esbuild.build(connectorBuildOptions(o));
  if (r.errors.length) throw new Error('connector bundle failed');
  return o.outfile;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const arg = k => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : undefined; };
  const dataFile = arg('--data'), out = arg('--out');
  if (!dataFile || !out) { console.error('usage: node tools/connector_bundle.mjs --data <data.json> --out <file.mjs>'); process.exit(2); }
  await bundleConnector({ outfile: path.resolve(out), data: JSON.parse(readFileSync(dataFile, 'utf8')) })
    .catch(e => { console.error('✗ ' + (e?.message ?? e)); process.exit(1); });
}
